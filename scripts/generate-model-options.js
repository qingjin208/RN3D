const fs = require('fs');
const path = require('path');

const projectRoot = path.resolve(__dirname, '..');
const modelsDir = path.join(projectRoot, 'assets', 'models');
const outputFile = path.join(projectRoot, 'src', 'constants', 'model-options.ts');

function toId(fileName) {
  const ext = path.extname(fileName).slice(1).toLowerCase();
  const base = path.basename(fileName, path.extname(fileName)).toLowerCase();
  const slug = base.replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '');
  return `${slug || 'model'}-${ext}`;
}

function relAssetPath(fileName) {
  const target = `../../assets/models/${fileName.replace(/\\/g, '/')}`;
  return JSON.stringify(target);
}

function main() {
  if (!fs.existsSync(modelsDir)) {
    throw new Error(`Missing models directory: ${modelsDir}`);
  }

  const files = fs.readdirSync(modelsDir);
  const modelFiles = files
    .filter((file) => {
      const ext = path.extname(file).toLowerCase();
      return ext === '.glb' || ext === '.obj';
    })
    .sort((a, b) => a.localeCompare(b));

  const fileSet = new Set(files.map((name) => name.toLowerCase()));
  const entries = modelFiles.map((fileName) => {
    const ext = path.extname(fileName).toLowerCase();
    const base = path.basename(fileName, ext);
    const mtlName = `${base}.mtl`;
    const hasMtl = ext === '.obj' && fileSet.has(mtlName.toLowerCase());

    return {
      id: toId(fileName),
      label: fileName,
      modelPath: relAssetPath(fileName),
      mtlPath: hasMtl ? relAssetPath(mtlName) : null,
    };
  });

  const lines = [];
  lines.push('// Auto-generated by scripts/generate-model-options.js.');
  lines.push('// Run `npm run models:sync` after adding/removing files in assets/models.');
  lines.push('');
  lines.push('export type ModelOption = {');
  lines.push('  id: string;');
  lines.push('  label: string;');
  lines.push('  modelModule: number;');
  lines.push('  mtlModule?: number;');
  lines.push('};');
  lines.push('');
  lines.push('export const MODEL_OPTIONS: ModelOption[] = [');

  for (const entry of entries) {
    lines.push('  {');
    lines.push(`    id: ${JSON.stringify(entry.id)},`);
    lines.push(`    label: ${JSON.stringify(entry.label)},`);
    lines.push(`    modelModule: require(${entry.modelPath}),`);
    if (entry.mtlPath) {
      lines.push(`    mtlModule: require(${entry.mtlPath}),`);
    }
    lines.push('  },');
  }

  lines.push('];');
  lines.push('');

  fs.writeFileSync(outputFile, `${lines.join('\n')}`, 'utf8');
  console.log(`Generated ${outputFile} with ${entries.length} model option(s).`);
}

main();
